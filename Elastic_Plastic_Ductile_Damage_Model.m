function [Material_State,D]=Elastic_Plastic_Ductile_Damage_Model(Material,Material_State,e)

%Material properties
%--------------------
E=Material.E;
v=Material.v;
f_y=Material.f_y;
Ep_eqv_0=Material.Ep_eqv_0;
g_f=Material.g_f;

%Values from previous iteration
%-----------------
e_i=Material_State.e;
s_i=Material_State.s_eff;   %Effective stress
k_i=Material_State.k;
k_D=Material_State.k_D;     %Doesn't require k_D_i because it is not in return mapping algorithm iterations  

%Constitutive law of elastic material
%----------------------------------------

E_hat=E/((1-2*v)*(1+v));
G=1/2*E/(1+v);

D_e= [E_hat*(1-v) E_hat*v     E_hat*v     0 0 0;...
      E_hat*v     E_hat*(1-v) E_hat*v     0 0 0;... 
      E_hat*v     E_hat*v     E_hat*(1-v) 0 0 0;... 
      0           0           0           G 0 0;...
      0           0           0           0 G 0;...
      0           0           0           0 0 G];

%Strain increment and elastic stress
%-----------------------------------
d_e=e-e_i;
s_e=s_i+D_e*d_e;

%Initial Solution
%------------------
i=0;
s=s_e;
d_k=0;
k=k_i;

while 1

i=i+1;
        
%Calculate yield function and its deriviatives
%----------------------------------------------
s_h=f_y+0.002*E*k;   %Hardening Law 
f=sqrt(0.5*((s(1)-s(2))^2+(s(2)-s(3))^2+(s(3)-s(1))^2)+3*(s(4)^2+s(5)^2+s(6)^2))-s_h;
if i==1 && f<0; break; end

d_f_d_s=[ -(s(2) - 2*s(1) + s(3))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2));...
          -(s(1) - 2*s(2) + s(3))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2));...
          -(s(1) + s(2) - 2*s(3))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2));...
          (3*s(4))/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2);...
          (3*s(5))/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2);...
          (3*s(6))/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2)];

d_d_f_d_d_s=[   1/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2) - (s(2) - 2*s(1) + s(3))^2/(4*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)), - 1/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2)) - ((s(1) - 2*s(2) + s(3))*(s(2) - 2*s(1) + s(3)))/(4*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)), - 1/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2)) - ((s(1) + s(2) - 2*s(3))*(s(2) - 2*s(1) + s(3)))/(4*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                   (3*s(4)*(s(2) - 2*s(1) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                   (3*s(5)*(s(2) - 2*s(1) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                   (3*s(6)*(s(2) - 2*s(1) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2));...
              - 1/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2)) - ((s(1) - 2*s(2) + s(3))*(s(2) - 2*s(1) + s(3)))/(4*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                        1/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2) - (s(1) - 2*s(2) + s(3))^2/(4*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)), - 1/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2)) - ((s(1) + s(2) - 2*s(3))*(s(1) - 2*s(2) + s(3)))/(4*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                   (3*s(4)*(s(1) - 2*s(2) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                   (3*s(5)*(s(1) - 2*s(2) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                   (3*s(6)*(s(1) - 2*s(2) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2));...
              - 1/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2)) - ((s(1) + s(2) - 2*s(3))*(s(2) - 2*s(1) + s(3)))/(4*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)), - 1/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2)) - ((s(1) + s(2) - 2*s(3))*(s(1) - 2*s(2) + s(3)))/(4*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                        1/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2) - (s(1) + s(2) - 2*s(3))^2/(4*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                   (3*s(4)*(s(1) + s(2) - 2*s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                   (3*s(5)*(s(1) + s(2) - 2*s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                   (3*s(6)*(s(1) + s(2) - 2*s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2));...
              (3*s(4)*(s(2) - 2*s(1) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                                                        (3*s(4)*(s(1) - 2*s(2) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                                                        (3*s(4)*(s(1) + s(2) - 2*s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)), 3/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2) - (9*s(4)^2)/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2),                                                                                    -(9*s(4)*s(5))/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2),                                                                                    -(9*s(4)*s(6))/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2);...
              (3*s(5)*(s(2) - 2*s(1) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                                                        (3*s(5)*(s(1) - 2*s(2) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                                                        (3*s(5)*(s(1) + s(2) - 2*s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                                    -(9*s(4)*s(5))/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2), 3/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2) - (9*s(5)^2)/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2),                                                                                    -(9*s(5)*s(6))/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2);...
              (3*s(6)*(s(2) - 2*s(1) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                                                        (3*s(6)*(s(1) - 2*s(2) + s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                                                        (3*s(6)*(s(1) + s(2) - 2*s(3)))/(2*((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)),                                                                                    -(9*s(4)*s(6))/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2),                                                                                    -(9*s(5)*s(6))/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2), 3/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(1/2) - (9*s(6)^2)/((s(1) - s(2))^2/2 + (s(1) - s(3))^2/2 + (s(2) - s(3))^2/2 + 3*s(4)^2 + 3*s(5)^2 + 3*s(6)^2)^(3/2)];...

h=0.002*E; %Hardening Law Derivative

d_f_d_k=-h;

h_c=1;

d_h_c_d_s=[0 ; 0 ; 0 ; 0 ; 0 ; 0];

%Calculate Risidue
%-------------------
r1=D_e\(s-s_e)+d_k*h_c*d_f_d_s;
r2=f;
r=[r1 ; r2];

if norm(r)<10^(-6)*f_y; break; end

%Calculate Jacobian
%--------------------
J11=inv(D_e)+d_k*(d_f_d_s*d_h_c_d_s'+h_c*d_d_f_d_d_s);
J12=h_c*d_f_d_s;
J21=d_f_d_s';
J22=d_f_d_k;
J=[J11 J12 ; J21 J22];

%Calculate Variation of Stress Vector and Hardening Parameter
%--------------------------------------------------------------
dd_sk=-J\r;
dd_s=dd_sk(1:6);
dd_k=dd_sk(7);

s=s+dd_s;
d_k=d_k+dd_k;
k=k_i+d_k;

end

%Calculate Tangential Stiffness Matrix
%---------------------------------------

if i==1 && f<0 
 
D_ep=D_e;
d=1-exp(-f_y*k_D/g_f);
s_eff=s;                         %Stress from return mapping algorithm is the effective stress
s=(1-d)*s_eff;
D=(1-d)*D_ep;

else
    
H=inv(inv(D_e)+h_c*d_k*d_d_f_d_d_s);
D_ep=H-(h_c*H*(d_f_d_s*d_f_d_s')*H)/(h+h_c*d_f_d_s'*H*d_f_d_s);

%Plastic Strain and its Derivative
%----------------------------------
e_p=e-D_e\s;
d_e_p_d_e=inv(D_e)*(D_e-D_ep);

%Principal Plastic Strain
%------------------------------
[Tp,Ep] = eig([e_p(1) e_p(4)/2 e_p(6)/2;...
               e_p(4)/2 e_p(2) e_p(5)/2;...
               e_p(6)/2 e_p(5)/2 e_p(3)]);
Ep=diag(Ep);                 
[Ep,I]=sort(Ep,'descend'); Tp=Tp(:,I);         

TTp=[Tp(1,1)^2 Tp(2,1)^2 Tp(3,1)^2 Tp(1,1)*Tp(2,1) Tp(2,1)*Tp(3,1) Tp(3,1)*Tp(1,1);...  %Transformation of Plastic Strain Matrix
     Tp(1,2)^2 Tp(2,2)^2 Tp(3,2)^2 Tp(1,2)*Tp(2,2) Tp(2,2)*Tp(3,2) Tp(3,2)*Tp(1,2);...
     Tp(1,3)^2 Tp(2,3)^2 Tp(3,3)^2 Tp(1,3)*Tp(2,3) Tp(2,3)*Tp(3,3) Tp(3,3)*Tp(1,3)];

%Equivelent Plastic Strain and Its Derivative 
%---------------------------------------------- 
Ep_eqv=sqrt(2/3)*sqrt(Ep(1)^2+Ep(2)^2+Ep(3)^2);

d_Ep_eqv_d_Ep=sqrt(2/3)*[Ep(1)/(Ep(1)^2 + Ep(2)^2+ Ep(3)^2)^(1/2);...                                           
                         Ep(2)/(Ep(1)^2 + Ep(2)^2+ Ep(3)^2)^(1/2);...
                         Ep(3)/(Ep(1)^2 + Ep(2)^2+ Ep(3)^2)^(1/2)];

d_Ep_eqv_d_ep=TTp'*d_Ep_eqv_d_Ep;

d_Ep_eqv_d_e=d_e_p_d_e'*d_Ep_eqv_d_ep;

%Loading and Unloading Conditions
%---------------------------------
if Ep_eqv-Ep_eqv_0>k_D 
k_D=Ep_eqv-Ep_eqv_0;    
d_k_D_d_Ep_eqv=1;
else
d_k_D_d_Ep_eqv=0;    
end

d_k_D_d_e=d_k_D_d_Ep_eqv*d_Ep_eqv_d_e;

%Damage and its derivative
%--------------------------
d=1-exp(-f_y*k_D/g_f);

d_d_d_k_D=f_y/g_f*exp(-f_y*k_D/g_f);

d_d_d_e=d_d_d_k_D*d_k_D_d_e;

%Stress and its derivative
%---------------------------
s_eff=s;         %Stress from return mapping algorithm is the effective stress
s=(1-d)*s_eff;
D=(1-d)*D_ep-s_eff*d_d_d_e';

end

%Final Material State
%---------------------
Material_State.e=e;
Material_State.s=s;
Material_State.s_eff=s_eff;
Material_State.k=k;
Material_State.k_D=k_D;
Material_State.d=d;

end
